<?php

namespace App\Filament\Resources;

use App\Filament\Resources\AuditResource\Pages;
use App\Models\Audit;
use App\Services\AiServiceInterface;
use Filament\Forms;
use Filament\Forms\Form;
use Filament\Notifications\Notification;
use Filament\Resources\Resource;
use Filament\Tables;
use Filament\Tables\Table;

class AuditResource extends Resource
{
    protected static ?string $model = Audit::class;

    protected static ?string $navigationIcon = 'heroicon-o-document-magnifying-glass';

    protected static ?string $navigationGroup = 'Internal Audit Operations';

    protected static ?int $navigationSort = 3;

    public static function form(Form $form): Form
    {
        return $form
            ->schema([
                Forms\Components\Section::make('Audit Engagement Details')
                    ->columns(3)
                    ->schema([
                        Forms\Components\TextInput::make('reference_number')
                            ->required()
                            ->default(fn () => 'AUD-'.date('Y').'-DSD-'.rand(100, 999))
                            ->maxLength(50),
                        Forms\Components\TextInput::make('title')
                            ->required()
                            ->maxLength(255)
                            ->columnSpan(2),
                        Forms\Components\Select::make('directorate_id')
                            ->relationship('directorate', 'name')
                            ->required()
                            ->searchable()
                            ->preload(),
                        Forms\Components\Select::make('checklist_id')
                            ->relationship('checklist', 'title')
                            ->searchable()
                            ->preload(),
                        Forms\Components\Select::make('lead_auditor_id')
                            ->relationship('leadAuditor', 'name')
                            ->required()
                            ->searchable()
                            ->preload(),
                        Forms\Components\Select::make('type')
                            ->options([
                                'internal_audit' => 'Internal Audit (DSD)',
                                'surveillance' => 'Surveillance Inspection',
                                'compliance_review' => 'Regulatory Compliance Review',
                                'special_inspection' => 'Special Duty Investigation',
                            ])
                            ->default('internal_audit')
                            ->required(),
                        Forms\Components\TextInput::make('location')
                            ->default('NCAA HQ Abuja')
                            ->required(),
                        Forms\Components\Select::make('status')
                            ->options([
                                'scheduled' => 'Scheduled',
                                'in_progress' => 'In Progress',
                                'review' => 'Under Review',
                                'completed' => 'Completed',
                                'closed' => 'Closed',
                            ])
                            ->default('scheduled')
                            ->required(),
                        Forms\Components\DatePicker::make('start_date')
                            ->default(now())
                            ->required(),
                        Forms\Components\DatePicker::make('end_date'),
                    ]),

                Forms\Components\Section::make('Scope & Executive Reporting')
                    ->schema([
                        Forms\Components\Textarea::make('scope')
                            ->rows(3)
                            ->placeholder('Specify stations, operational bases, aircraft, logbooks, or facilities covered.'),
                        Forms\Components\Textarea::make('executive_summary')
                            ->rows(4)
                            ->placeholder('Lead auditor executive summary observations.'),
                        Forms\Components\MarkdownEditor::make('ai_executive_summary')
                            ->label('AI-Generated Executive Audit Summary')
                            ->helperText('Generated by NCAA AI Audit Engine assessing findings, severity, and compliance ratings.')
                            ->columnSpanFull(),
                    ]),
            ]);
    }

    public static function table(Table $table): Table
    {
        return $table
            ->columns([
                Tables\Columns\TextColumn::make('reference_number')
                    ->badge()
                    ->color('primary')
                    ->searchable()
                    ->sortable(),
                Tables\Columns\TextColumn::make('title')
                    ->searchable()
                    ->weight('bold')
                    ->limit(35),
                Tables\Columns\TextColumn::make('directorate.code')
                    ->label('Target')
                    ->badge()
                    ->color('info')
                    ->sortable(),
                Tables\Columns\TextColumn::make('location')
                    ->searchable(),
                Tables\Columns\TextColumn::make('status')
                    ->badge()
                    ->color(fn (string $state): string => match ($state) {
                        'scheduled' => 'gray',
                        'in_progress' => 'warning',
                        'review' => 'info',
                        'completed' => 'success',
                        'closed' => 'gray',
                        default => 'secondary',
                    }),
                Tables\Columns\TextColumn::make('findings_count')
                    ->counts('findings')
                    ->label('Findings')
                    ->badge()
                    ->color(fn (int $state): string => $state > 0 ? 'danger' : 'success'),
                Tables\Columns\TextColumn::make('start_date')
                    ->date()
                    ->sortable(),
            ])
            ->actions([
                Tables\Actions\Action::make('generateAiSummary')
                    ->label('AI Summary')
                    ->icon('heroicon-m-sparkles')
                    ->color('success')
                    ->action(function (Audit $record, AiServiceInterface $ai) {
                        $crit = $record->findings()->where('severity', 'critical')->count();
                        $maj = $record->findings()->where('severity', 'major')->count();
                        $min = $record->findings()->where('severity', 'minor')->count();

                        $summary = $ai->generateExecutiveSummary(
                            $record->title,
                            $record->directorate ? $record->directorate->name : 'NCAA Unit',
                            $record->compliance_score,
                            ['critical' => $crit, 'major' => $maj, 'minor' => $min]
                        );

                        $record->update(['ai_executive_summary' => $summary]);

                        Notification::make()
                            ->title('AI Executive Summary Generated')
                            ->success()
                            ->send();
                    }),
                Tables\Actions\EditAction::make(),
            ])
            ->bulkActions([
                Tables\Actions\BulkActionGroup::make([
                    Tables\Actions\DeleteBulkAction::make(),
                ]),
            ]);
    }

    public static function getPages(): array
    {
        return [
            'index' => Pages\ListAudits::route('/'),
            'create' => Pages\CreateAudit::route('/create'),
            'edit' => Pages\EditAudit::route('/{record}/edit'),
        ];
    }
}
